"""The local file listing each seeded user's sign-in name and password.

The database keeps only password hashes, so this file is the one place the
seeded passwords can be read. It is git-ignored and never committed.
"""

from collections.abc import Iterable
from datetime import datetime
from pathlib import Path

from clinical_notes_api.config import REPOSITORY_ROOT
from clinical_notes_api.seed.load import Credential

CREDENTIALS_PATH = REPOSITORY_ROOT / "credentials.local.md"

ROLE_NAMES = {
    "ADMIN": "Administrator",
    "CLINICIAN": "Clinician",
    "REVIEWER": "Reviewer",
    "READONLY_AUDITOR": "Read-only auditor",
}


def render_credentials(
    credentials: Iterable[Credential],
    generated_at: datetime,
) -> str:
    # The administrator first: the account most often needed.
    ordered = sorted(credentials, key=lambda credential: credential.role != "ADMIN")
    rows = "\n".join(
        f"| `{credential.username}` | {credential.display_name} "
        f"| {ROLE_NAMES.get(credential.role, credential.role)} "
        f"| `{credential.password}` |"
        for credential in ordered
    )
    return (
        "# Local sign-in credentials\n"
        "\n"
        f"Generated by `clinical-notes-seed` on "
        f"{generated_at:%Y-%m-%d %H:%M} UTC. Seeding again replaces every "
        "password.\n"
        "\n"
        "Never commit or share this file. It is listed in `.gitignore`.\n"
        "\n"
        "| Username | Name | Role | Password |\n"
        "| --- | --- | --- | --- |\n"
        f"{rows}\n"
    )


def write_credentials(
    path: Path,
    credentials: Iterable[Credential],
    generated_at: datetime,
) -> None:
    path.write_text(
        render_credentials(credentials, generated_at),
        encoding="utf-8",
        newline="\n",
    )
